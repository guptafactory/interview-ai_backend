import { GoogleGenAI } from "@google/genai";
import { env } from "../config/env.js";
import { AppError } from "../utils/AppError.js";
import {
  interviewReportZodSchema,
  interviewReportJsonSchema,
  resumePdfJsonSchema,
  resumePdfZodSchema,
} from "../validators/ai.validator.js";

const ai = new GoogleGenAI({
  apiKey: env.GEMINI_API_KEY,
});

async function generateReportByAI(
  resumeContent,
  selfDescription,
  jobDescription,
) {
  const prompt = `
        Generate an interview preparation report for the candidate.

        Candidate Resume:
        ${resumeContent}

        Candidate Self Description:
        ${selfDescription}

        Job Description:
        ${jobDescription}

        Analyze the candidate against the job description and generate:
        1. A match score from 0-100.
        2. Technical interview questions.
        3. Behavioral interview questions.
        4. Skill gaps.
        5. A practical day-wise preparation plan with doable tasks.

        The questions and preparation plan should be specific to this candidate and this job description.`;

  let interaction;
  try {
    interaction = await ai.interactions.create({
      model: "gemini-3.5-flash-lite",
      input: prompt,
      response_format: {
        type: "text",
        mime_type: "application/json",
        schema: interviewReportJsonSchema,
      },
    });
  } catch (cause) {
    const error = new AppError(
      "The AI service is unavailable right now. Please try again shortly.",
      503,
      "AI_UNAVAILABLE",
    );
    error.cause = cause; // logged, never sent to the client
    throw error;
  }

  let parsedOutput;
  try {
    parsedOutput = JSON.parse(interaction.output_text);
  } catch {
    throw new AppError(
      "The AI returned a response we could not read",
      502,
      "AI_RESPONSE_INVALID",
    );
  }

  const validatedReport = interviewReportZodSchema.safeParse(parsedOutput);
  if (!validatedReport.success) {
    throw new AppError(
      "The AI returned a report in an unexpected format",
      502,
      "AI_RESPONSE_INVALID",
      validatedReport.error.issues.map((issue) => ({
        field: issue.path.join("."),
        message: issue.message,
      })),
    );
  }

  return validatedReport.data;
}

